create table users (
    id         bigint generated by default as identity primary key,
    email      varchar(255) not null unique,
    name       varchar(255) not null,
    role       varchar(20)  not null,
    created_at timestamp(6) with time zone not null
);

create table ticket (
    id          bigint generated by default as identity primary key,
    title       varchar(255)  not null,
    description varchar(4000) not null,
    status      varchar(20)   not null,
    priority    varchar(20)   not null,
    reporter_id bigint        not null references users (id),
    assignee_id bigint        references users (id),
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null
);

create table comment (
    id         bigint generated by default as identity primary key,
    ticket_id  bigint        not null references ticket (id),
    author_id  bigint        not null references users (id),
    body       varchar(4000) not null,
    created_at timestamp(6) with time zone not null
);

-- Postgres indexes primary keys and unique columns automatically, but not
-- foreign keys. These match the repository queries (filter by status or
-- assignee, comments by ticket) and speed up joins on reporter.
create index ticket_status_idx on ticket (status);
create index ticket_assignee_idx on ticket (assignee_id);
create index ticket_reporter_idx on ticket (reporter_id);
create index comment_ticket_idx on comment (ticket_id);
