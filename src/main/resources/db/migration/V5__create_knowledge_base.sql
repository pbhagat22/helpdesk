-- Knowledge base: help articles written by staff, searchable by meaning (not just keywords).

-- pgvector adds the vector column type, distance operators and vector indexes. Creating an
-- extension needs a superuser (locally) or rds_superuser (RDS's master user).
create extension if not exists vector;

create table kb_article (
    id         bigint generated by default as identity primary key,
    title      varchar(255)   not null,
    body       varchar(20000) not null,
    author_id  bigint         not null references users (id),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null
);

create index kb_article_author_idx on kb_article (author_id);

-- Each article is split into chunks of a few paragraphs, and each chunk gets an embedding:
-- 512 numbers from Amazon Titan Text Embeddings V2 that capture what the text means. Texts with
-- similar meaning have embeddings that point in a similar direction, so "can't sign in" is
-- close to an article about "login problems" even without a shared word.
-- Chunks are rebuilt whenever their article changes, and deleted with it (on delete cascade).
create table kb_chunk (
    id          bigint generated by default as identity primary key,
    article_id  bigint      not null references kb_article (id) on delete cascade,
    chunk_index integer     not null,
    content     text        not null,
    embedding   vector(512) not null,
    -- Also serves as the index on article_id
    unique (article_id, chunk_index)
);

-- HNSW: an approximate nearest-neighbour index, so "the 20 closest chunks" doesn't have to
-- compare the query with every row. vector_cosine_ops matches the <=> (cosine distance)
-- operator used in the search query.
create index kb_chunk_embedding_idx on kb_chunk using hnsw (embedding vector_cosine_ops);
