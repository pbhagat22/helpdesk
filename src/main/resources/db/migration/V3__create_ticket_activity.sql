-- History of what happened to each ticket, built from the Kafka ticket events.
--
-- ticket_id and actor_id are plain columns, not foreign keys: this table belongs to the
-- event consumer, which only knows what the events tell it. That keeps it independent of
-- the ticket tables (it could move to another service with its own database).
create table ticket_activity (
    id          bigint generated by default as identity primary key,
    -- Kafka can deliver an event more than once; the unique id lets us store it only once
    event_id    uuid        not null unique,
    ticket_id   bigint      not null,
    type        varchar(20) not null,
    actor_id    bigint      not null,
    -- Type-specific facts, e.g. {"from": "OPEN", "to": "IN_PROGRESS"}, stored as JSON
    details     jsonb       not null,
    occurred_at timestamp(6) with time zone not null
);

create index ticket_activity_ticket_idx on ticket_activity (ticket_id, occurred_at);
