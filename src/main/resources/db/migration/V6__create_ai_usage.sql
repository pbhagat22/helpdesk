-- One row per Bedrock call (chat model or embedding), with the tokens Bedrock bills for.
-- Read by the admin usage report and by the token budgets.
--
-- user_id is a plain column, not a foreign key: this is a ledger, so its rows are never
-- changed or cascaded. It's null for background work (triage), which no user started.
create table ai_usage (
    id            bigint generated by default as identity primary key,
    user_id       bigint,
    feature       varchar(20)  not null,
    model         varchar(100) not null,
    input_tokens  integer      not null,
    output_tokens integer      not null,
    created_at    timestamp(6) with time zone not null
);

-- Budgets add up one user's tokens since midnight; the report reads a date range.
create index ai_usage_user_created_idx on ai_usage (user_id, created_at);
create index ai_usage_created_idx on ai_usage (created_at);
