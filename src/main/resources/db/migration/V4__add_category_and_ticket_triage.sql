-- Tickets get a category, set by staff. Nullable: existing tickets and new ones start
-- uncategorised (customers don't choose it).
alter table ticket add column category varchar(20);

-- The AI's triage suggestion for a ticket, written by the Kafka consumer group
-- "helpdesk-triage" after a ticket is created. Staff decide whether to apply it.
--
-- Like ticket_activity, ticket_id is a plain column, not a foreign key: the table belongs
-- to the consumer. It's unique, so a redelivered event can't store a second suggestion.
create table ticket_triage (
    id         bigint generated by default as identity primary key,
    ticket_id  bigint       not null unique,
    priority   varchar(20)  not null,
    category   varchar(20)  not null,
    -- One sentence from the model explaining its choice, shown to staff
    reason     varchar(500) not null,
    -- Which Bedrock model made the suggestion, to compare models later
    model      varchar(100) not null,
    created_at timestamp(6) with time zone not null
);
